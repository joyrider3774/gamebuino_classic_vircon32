// -----------------------------------------------------------------------------
//   Quit-confirmation dialog (Start, while a game is running)
// -----------------------------------------------------------------------------
// Direct port of the sibling tinyjoypad_vircon32 project's own dialog - see
// that project's own CLAUDE.md for the full history of why it was added
// (Start instantly quitting risked losing real progress on an accidental
// press). While this dialog is up the current game's own update() is not
// called at all (see main()'s dispatch loop below), so gameplay is fully
// frozen rather than continuing to run behind the dialog.
bool confirmingQuit = false;
int confirmSelection = 0; // 0 = NO (default - the safer choice), 1 = YES
bool prevConfirmLeft = false;
bool prevConfirmRight = false;
bool prevConfirmA = false;

void drawConfirmQuitDialog()
{
    int boxX = 160, boxY = 110, boxW = 320, boxH = 140;
    int borderThickness = 6;

    md_drawSolidRect( boxX, boxY, boxW, boxH, color_white );
    md_drawSolidRect
    (
        boxX + borderThickness, boxY + borderThickness,
        boxW - ( borderThickness * 2 ), boxH - ( borderThickness * 2 ),
        color_black
    );

    print_at( boxX + 125, boxY + 20, "CONFIRM" );
    print_at( boxX + 95, boxY + 55, "QUIT TO MENU?" );

    int yesX = boxX + 100;
    int noX = boxX + 210;
    int optionsY = boxY + 95;

    if( confirmSelection == 1 )
      print_at( yesX - 15, optionsY, ">" );
    else
      print_at( noX - 15, optionsY, ">" );

    print_at( yesX, optionsY, "YES" );
    print_at( noX, optionsY, "NO" );
}

// -----------------------------------------------------------------------------
//   Pixel-grid overlay (Button L, while a game is running)
// -----------------------------------------------------------------------------
// Direct port of the sibling tinyjoypad_vircon32 project's own toggle - see
// that project's own CLAUDE.md ("A pixel-grid presentation overlay...") for
// the full design rationale, including a real "toggle doesn't visually take
// effect" bug found and fixed there. That specific bug doesn't reproduce
// here: unlike that project's own obonoCoreShim-lineage games (which can
// skip their own redraw indefinitely on an unchanging frame), every
// Gamebuino game here redraws through gbUpdate()/gbRenderFrame(), which
// unconditionally clears and fully repaints the whole screen on every real
// logic tick (matching real hardware's own default persistence=false
// behavior) - so a stale grid line left behind by a toggle is naturally
// repainted over within at most one game tick, with no forced onResume
// needed for correctness. The onResume call below is still wired up (and
// still gated the same way) purely for parity with the sibling project's
// own architecture, in case some future game here ever adopts a
// persistence=true-style skipped redraw.
//
// Bound to Button L rather than the sibling project's own Button X, since
// X is already spoken for here (it's real Gamebuino Button C - see
// machineDependent.h's own md_inputC()); L is otherwise unused by this
// project (Gamebuino Classic's own real hardware has no L/R shoulder
// buttons at all).
//
// Off by default and only ever toggled/rendered while a game is actually
// running (never on the menu, and not drawn on top of the quit-
// confirmation dialog either) - matching the sibling project's own
// `currentGameIndex != -1` gating exactly.
bool pixelGridEnabled = false;
bool prevGridButton = false;

// Sound on/off - Button Y (unused elsewhere: A=real Button A, B=real Button
// B, X=real Button C, L=pixel-grid toggle, Start=quit dialog), toggled
// globally rather than gated to gameplay-only the way the pixel-grid toggle
// is - matches the sibling tinyjoypad_vircon32 project's own mute toggle,
// which likewise works everywhere (menu, gameplay, dialog), not just
// mid-game. Implemented via Vircon32's own real SPU_GlobalVolume hardware
// register (set_global_volume(), range 0-2) rather than gating each
// md_playTone() call individually.
bool audioMuted = false;
bool prevMuteButton = false;

// Real-solid-gray-color toggle - Button R (unused elsewhere: A/B/X/L/Y/
// Start are all already spoken for above), flipped globally the same way
// the mute toggle is (not gated to gameplay-only), since it's a rendering
// preference rather than a gameplay feature. `gbRealGrayColor` itself
// (gamebuinoShim.h/.c) is what every drawing primitive/gbRenderFrame()
// actually reads every frame - this is just the button edge-detect that
// flips it.
bool prevGrayButton = false;

void drawPixelGridOverlay()
{
    select_texture( PIXELGRID_TEXTURE_ID );
    select_region( 0 );
    draw_region_at( ORIGIN_X, ORIGIN_Y );
}

void main()
{
    select_gamepad( 0 );

    md_initVideo();
    md_initAudio();

    addGames();
    menu_init();

    while( true )
    {
        bool start = md_inputStart();
        bool justStarted = ( start && !prevStart );
        prevStart = start;

        if( confirmingQuit )
        {
            bool left = md_inputLeft();
            bool right = md_inputRight();
            bool a = md_inputA();
            bool justLeft = ( left && !prevConfirmLeft );
            bool justRight = ( right && !prevConfirmRight );
            bool justA = ( a && !prevConfirmA );
            prevConfirmLeft = left;
            prevConfirmRight = right;
            prevConfirmA = a;

            if( justLeft || justRight )
              confirmSelection = 1 - confirmSelection;

            if( justA )
            {
                // The same physical press that just confirmed this dialog
                // must not also register as a fresh press once we're back
                // in the menu (instantly launching whatever's highlighted)
                // or back in gameplay (an unwanted in-game action the
                // instant it resumes) - md_inputA() is the single shared
                // gate every gbPressed(BTN_A)/menu A-read goes through, so
                // arming it here covers both destinations.
                md_armInputAGate();
                if( confirmSelection == 1 )
                {
                    // md_stopTone() alone only clears the one-shot voice
                    // pool (gbPlayTick()/OK()/Cancel()) - the tracker
                    // engine's own per-channel state (gbTrackIsPlaying[]/
                    // gbPatternIsPlaying[]/gbNotePlaying[]/gbActiveVoice[])
                    // isn't reset by it at all, so a game quit mid-track
                    // (e.g. 101Starships' own continuous background music)
                    // would otherwise leave that state dangling - harmless
                    // once a fresh game's own gbBegin() resets it, but real,
                    // audible silence is the whole point of quitting to the
                    // menu, not "silent until the next launch happens to
                    // reset it." gbStopTrackAll() cascades down through
                    // gbStopPattern()/gbStopNoteChannel(), which also calls
                    // md_trackerVoiceStop() on every active tracker voice.
                    gbStopTrackAll();
                    md_stopTone();
                    currentGameIndex = -1;
                    menu_init();
                }
                else if( menu_getGame( currentGameIndex )->onResume != NULL )
                  menu_getGame( currentGameIndex )->onResume();
                confirmingQuit = false;
            }
            else if( justStarted )
            {
                // pressing Start again cancels, same as selecting NO
                if( menu_getGame( currentGameIndex )->onResume != NULL )
                  menu_getGame( currentGameIndex )->onResume();
                confirmingQuit = false;
            }

            drawConfirmQuitDialog();
        }
        else if( currentGameIndex != -1 && justStarted )
        {
            confirmingQuit = true;
            confirmSelection = 0;
            // Arm against whatever Left/Right/A happen to already be held
            // at this exact moment, the same reasoning as
            // md_armInputAGate() - otherwise a leftover press from
            // gameplay could immediately register as a dialog input.
            prevConfirmLeft = md_inputLeft();
            prevConfirmRight = md_inputRight();
            prevConfirmA = md_inputA();
            drawConfirmQuitDialog();
        }
        else if( currentGameIndex == -1 )
        {
            int chosen = menu_update();
            if( chosen != -1 )
            {
                currentGameIndex = chosen;
                md_armInputAGate();
                md_beginFrame();

                // Resolve/load this game's own persistent EEPROM slot
                // (looked up by its title, not by chosen/registration
                // index - see eepromShim.c) before init() runs, since a
                // game's own init() is what actually calls
                // eeprom_read_byte()/etc to load its saved high score.
                eepromSelectGame( menu_getGame( chosen )->title );

                menu_getGame( chosen )->init();
            }
        }
        else
        {
            menu_getGame( currentGameIndex )->update();
        }

        // Button L toggles the pixel-grid overlay - only meaningful during
        // actual gameplay (matching drawPixelGridOverlay()'s own render
        // gate below), so the press is only even looked at then; toggling
        // it while on the menu or mid quit-dialog would otherwise be a
        // silent, confusing no-op.
        if( currentGameIndex != -1 && !confirmingQuit )
        {
            bool gridButton = ( gamepad_button_l() > 0 );
            if( gridButton && !prevGridButton )
            {
                pixelGridEnabled = !pixelGridEnabled;

                if( menu_getGame( currentGameIndex )->onResume != NULL )
                  menu_getGame( currentGameIndex )->onResume();
            }
            prevGridButton = gridButton;
        }

        if( currentGameIndex != -1 && !confirmingQuit && pixelGridEnabled )
          drawPixelGridOverlay();

        // Button Y toggles sound globally - unlike the pixel-grid toggle
        // above, deliberately NOT gated to "a game is running": the menu
        // itself is silent today, but gating this to gameplay-only would be
        // a surprising inconsistency, and would mean muting mid-game then
        // returning to the menu and back couldn't be done from the menu
        // screen itself.
        bool muteButton = ( gamepad_button_y() > 0 );
        if( muteButton && !prevMuteButton )
        {
            audioMuted = !audioMuted;
            if( audioMuted )
              set_global_volume( 0.0 );
            else
              set_global_volume( 1.0 );
        }
        prevMuteButton = muteButton;

        // Button R toggles real-solid-gray-color rendering globally, exactly
        // like the mute toggle above - see prevGrayButton's own comment.
        bool grayButton = ( gamepad_button_r() > 0 );
        if( grayButton && !prevGrayButton )
          gbRealGrayColor = !gbRealGrayColor;
        prevGrayButton = grayButton;

        md_updateAudio();
        md_endFrame();
    }
}
