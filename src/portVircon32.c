// 84 LCD px * 7 = 588, 48 * 7 = 336 - centered in the 640x360 screen with a
// 26px bar left/right and an 12px bar top/bottom.
#define TILE_SCALE   7
#define ATLAS_GRID   16
#define TILE_W       TILE_SCALE
#define TILE_H       ( 8 * TILE_SCALE )
#define ORIGIN_X     26
#define ORIGIN_Y     12

#define COLUMNS_TEXTURE_ID 0
// libs/PlayNote/sounds/wt_square.wav - a real, hard-edged 50%-duty square
// wave (tools/gen_square_wavetable.py), matching real Gamebuino Classic
// hardware's own default instrument exactly: real Sound.cpp drives its
// piezo speaker with a genuine 2-level PWM square wave (toggling
// _chanState high/low every half-period in updateOutput()/generateOutput() -
// no duty-cycle control of its own, amplitude is the only thing a real
// instrument step varies), not PlayNote's own generic sawtooth sample.
#define WAVETABLE_SOUND_ID 0
// See the sibling tinyjoypad_vircon32 project's own portVircon32.c for the
// full story on why this needs to be short enough to keep the SPU's own
// hardware speed-register clamp (0-128) from silently ceiling every note
// above ~2.7kHz to the same pitch - 256 samples raises that ceiling to
// ~22kHz, comfortably covering anything a Gamebuino Classic game's own
// Sound()-equivalent note range is likely to ask for.
#define WAVETABLE_PERIOD_SAMPLES 256

// Menu game-select thumbnails: one real gameplay screenshot per game
// (assets/thumbnails.png, cropped/scaled from an actual Puppeteer capture of
// the game running, matching the sibling tinyjoypad_vircon32 project's own
// "built offline from actual play captures" discipline - not a mockup).
// Grew from a 4x1 grid (4 cells) to 4x3 (12) to 4x6 (1024x768, 24 cells)
// once the 10 games ported after SNAKE ABC each had a real capture ready -
// region ids assigned in addGames()'s own registration order (NOT the
// menu's own alphabetical display order - see menu.c's own selection-
// sort). Same THUMBNAIL_W/H/grid-of-regions design as the sibling
// tinyjoypad_vircon32 project's own thumbnails.png.
//
// Batch 3 (20 more games) needed 20 more cells, but simply growing this
// same texture taller (to 4x11, 1024x1408) was tried first and rejected:
// `packrom` genuinely refused it ("texture size is larger than allowed by
// Vircon32 GPU") - confirmed empirically, not assumed. Real Vircon32 GPU
// textures are capped at 1024x1024 - grown this texture up to exactly that
// ceiling instead (4x8, 1024x1024, 32 cells - region ids 0-31, holding
// registration indices 0-31), and added a second, small
// THUMBNAILS2_TEXTURE_ID (below) for the remaining registration indices
// (32 and up) rather than trying to squeeze everything into one texture -
// the second-texture approach this file's own earlier comment had already
// anticipated, just triggered by hitting the real 1024x1024 ceiling instead
// of running out of an arbitrarily-sized single texture.
#define THUMBNAILS_TEXTURE_ID 1
#define THUMBNAIL_W MD_THUMBNAIL_WIDTH
#define THUMBNAIL_H MD_THUMBNAIL_HEIGHT
#define THUMBNAIL_GRID_COLS 4
#define THUMBNAIL_GRID_ROWS 8
#define THUMBNAIL_SPLIT 32

// Pixel-grid overlay (see drawPixelGridOverlay() below) - one pre-baked
// 588x336 texture (assets/pixelgrid.png, generated by tools/gen_pixelgrid.py
// - a transparent background with opaque black 1px lines at every
// TILE_SCALE-pixel boundary in both directions) instead of drawing 132
// individual md_drawSolidRect() lines by hand. Direct port of the sibling
// tinyjoypad_vircon32 project's own identical design - see that project's
// own portVircon32.c/CLAUDE.md for the full rationale (relies on
// blending_alpha, the GPU's own default mode, so only the opaque grid-line
// pixels actually affect the screen). Texture id 2.
#define PIXELGRID_TEXTURE_ID 2

// Second thumbnail atlas - see THUMBNAILS_TEXTURE_ID's own comment above
// for why this exists (the first texture is already at the real, confirmed
// 1024x1024 Vircon32 GPU texture size ceiling). Holds registration indices
// THUMBNAIL_SPLIT..THUMBNAIL_SPLIT2-1. Appended after PIXELGRID_TEXTURE_ID
// (id 3) rather than inserted right after THUMBNAILS_TEXTURE_ID, matching
// this project's own "append, don't insert" precedent for texture ids (see
// the sibling tinyjoypad_vircon32 project's own CLAUDE.md). Grown from 4x6
// (24 cells) to 4x8 (32 cells, 1024x1024) once batch-5 porting brought the
// real registered-game count to 64 (indices 32-63 - exactly 32 needed) -
// this texture is at the exact same real, confirmed 1024x1024 GPU ceiling
// the first texture already hit, with zero cells of headroom left.
#define THUMBNAILS2_TEXTURE_ID 3
#define THUMBNAIL2_GRID_COLS 4
#define THUMBNAIL2_GRID_ROWS 8
#define THUMBNAIL_SPLIT2 64

// Third thumbnail atlas, needed the moment the real registered-game count
// passed 64 (both earlier textures are already at the real 1024x1024 GPU
// ceiling with zero cells to spare) - holds registration indices
// THUMBNAIL_SPLIT2 and up. Appended after GRAYCOLUMNS_TEXTURE_ID (id 4)
// rather than inserted earlier, matching this project's own "append, don't
// insert" precedent for texture ids. Grown from 4x3 (12 cells, 1024x384) to
// 4x5 (20 cells, 1024x640) once the "port all staged tier 1 games" batch
// brought the real registered-game count to 79, then to 4x6 (24 cells,
// 1024x768) once the "port all tier 2 games" batch brought it to 84 (the
// previous 20-cell capacity was now exactly full, zero cells to spare) -
// the same "modest headroom past the real current total" reason as every
// earlier thumbnail-atlas growth in this project.
#define THUMBNAILS3_TEXTURE_ID 5
#define THUMBNAIL3_GRID_COLS 4
#define THUMBNAIL3_GRID_ROWS 6
#define THUMBNAIL_SPLIT3 88

// Fourth thumbnail atlas, needed the moment the real registered-game count
// passed 88 (the third texture's own 4x6/24-cell capacity, added during
// the Tier 2 batch, was by then exactly full - zero cells to spare) -
// holds registration indices THUMBNAIL_SPLIT3 and up. Appended after
// THUMBNAILS3_TEXTURE_ID (id 5) rather than inserted earlier, matching
// this project's own "append, don't insert" precedent for texture ids.
// Starts at a real 4x3 (12 cells, 1024x384), the same "modest headroom"
// starting size every earlier thumbnail atlas in this project began at.
#define THUMBNAILS4_TEXTURE_ID 6
#define THUMBNAIL4_GRID_COLS 4
#define THUMBNAIL4_GRID_ROWS 3
#define THUMBNAIL_COUNT 99

// Same 256-tile-per-byte-value layout as COLUMNS_TEXTURE_ID above (see
// tools/gen_column_atlas_gray.py), but "lit" bits are a real opaque
// mid-gray and "off" bits are fully transparent - only ever selected by
// md_drawColumnGray() below, which gbRenderFrame() calls as a second,
// targeted pass whenever the runtime gbRealGrayColor toggle is on (see
// gamebuinoShim.h's own Configuration section). Appended after
// THUMBNAILS2_TEXTURE_ID, matching this project's own "append, don't
// insert" precedent for texture ids.
#define GRAYCOLUMNS_TEXTURE_ID 4

void md_initVideo()
{
    select_texture( COLUMNS_TEXTURE_ID );

    define_region_matrix
    (
        0,                              // first_id (region id == byte value)
        0, 0, TILE_W - 1, TILE_H - 1,   // first tile bounds
        0, 0,                           // hotspot at top-left
        ATLAS_GRID, ATLAS_GRID,         // 16x16 = 256 tiles
        0                               // no gap between tiles
    );

    select_texture( THUMBNAILS_TEXTURE_ID );

    define_region_matrix
    (
        0,                                          // first_id == game index
        0, 0, THUMBNAIL_W - 1, THUMBNAIL_H - 1,     // first tile bounds
        0, 0,                                       // hotspot at top-left
        THUMBNAIL_GRID_COLS, THUMBNAIL_GRID_ROWS,
        0
    );

    select_texture( PIXELGRID_TEXTURE_ID );
    select_region( 0 );
    define_region( 0, 0, LCD_WIDTH * TILE_SCALE - 1, LCD_HEIGHT * TILE_SCALE - 1, 0, 0 );

    select_texture( THUMBNAILS2_TEXTURE_ID );

    define_region_matrix
    (
        0,                                          // first_id == (game index - THUMBNAIL_SPLIT)
        0, 0, THUMBNAIL_W - 1, THUMBNAIL_H - 1,     // first tile bounds
        0, 0,                                       // hotspot at top-left
        THUMBNAIL2_GRID_COLS, THUMBNAIL2_GRID_ROWS,
        0
    );

    select_texture( THUMBNAILS3_TEXTURE_ID );

    define_region_matrix
    (
        0,                                          // first_id == (game index - THUMBNAIL_SPLIT2)
        0, 0, THUMBNAIL_W - 1, THUMBNAIL_H - 1,     // first tile bounds
        0, 0,                                       // hotspot at top-left
        THUMBNAIL3_GRID_COLS, THUMBNAIL3_GRID_ROWS,
        0
    );

    select_texture( THUMBNAILS4_TEXTURE_ID );

    define_region_matrix
    (
        0,                                          // first_id == (game index - THUMBNAIL_SPLIT3)
        0, 0, THUMBNAIL_W - 1, THUMBNAIL_H - 1,     // first tile bounds
        0, 0,                                       // hotspot at top-left
        THUMBNAIL4_GRID_COLS, THUMBNAIL4_GRID_ROWS,
        0
    );

    select_texture( GRAYCOLUMNS_TEXTURE_ID );

    define_region_matrix
    (
        0,                              // first_id (region id == byte value)
        0, 0, TILE_W - 1, TILE_H - 1,   // first tile bounds
        0, 0,                           // hotspot at top-left
        ATLAS_GRID, ATLAS_GRID,         // 16x16 = 256 tiles
        0                               // no gap between tiles
    );

    set_multiply_color( color_white );
}

int md_getThumbnailCount()
{
    return THUMBNAIL_COUNT;
}

void md_drawGameThumbnail( int gameIndex, int x, int y )
{
    if( gameIndex < 0 || gameIndex >= THUMBNAIL_COUNT )
      return;

    if( gameIndex < THUMBNAIL_SPLIT )
    {
        select_texture( THUMBNAILS_TEXTURE_ID );
        select_region( gameIndex );
    }
    else if( gameIndex < THUMBNAIL_SPLIT2 )
    {
        select_texture( THUMBNAILS2_TEXTURE_ID );
        select_region( gameIndex - THUMBNAIL_SPLIT );
    }
    else if( gameIndex < THUMBNAIL_SPLIT3 )
    {
        select_texture( THUMBNAILS3_TEXTURE_ID );
        select_region( gameIndex - THUMBNAIL_SPLIT2 );
    }
    else
    {
        select_texture( THUMBNAILS4_TEXTURE_ID );
        select_region( gameIndex - THUMBNAIL_SPLIT3 );
    }
    draw_region_at( x, y );
}

// Solid-color filled rectangle - reuses the columns atlas's own region 255
// (byte value 0xFF - all 8 pixels lit, a plain TILE_W x TILE_H solid white
// tile already loaded for md_drawColumn) rather than adding a whole new
// texture asset just for this: video.h has no rectangle-fill primitive of
// its own, only region blits, so the standard trick (same one the sibling
// tinyjoypad_vircon32 project's own md_drawSolidRect() already uses) is to
// tint a solid region via set_multiply_color() and stretch it to any size
// via set_drawing_scale()+draw_region_zoomed_at(). Used by the quit-
// confirmation dialog below (white outline, black interior) - restores the
// multiply color/scale afterward since every other draw call in this file
// (md_drawColumn, print_at) assumes the neutral white/1x state left by
// md_initVideo().
void md_drawSolidRect( int x, int y, int w, int h, int color )
{
    select_texture( COLUMNS_TEXTURE_ID );
    select_region( 255 );
    set_multiply_color( color );
    set_drawing_scale( (float)w / TILE_W, (float)h / TILE_H );
    draw_region_zoomed_at( x, y );
    set_multiply_color( color_white );
    set_drawing_scale( 1.0, 1.0 );
}

// Clears to WHITE, not black - a real Nokia 5110/PCD8544 LCD (unlike the
// sibling tinyjoypad_vircon32 project's own self-illuminating SSD1306
// OLED) has a naturally light background, with a "set" pixel drawn as dark
// ink on top of it (see tools/gen_column_atlas.py's own header comment for
// the full story - a real bug found via direct user report, "colors seem
// inverted", not the original design). md_drawColumn() below relies on
// this exact color matching its own "skip value==0" optimization: a
// value of 0 (all 8 pixels off) is only ever a safe no-op because the
// frame was already cleared to the SAME color those "off" pixels would
// have drawn anyway.
void md_beginFrame()
{
    clear_screen( color_white );
    select_texture( COLUMNS_TEXTURE_ID );
}

void md_drawColumn( int col, int page, int value )
{
    // Vircon32 ints are full 32-bit words with no implicit byte truncation -
    // see the sibling tinyjoypad_vircon32 project's own extensively-
    // documented history of bugs from assuming AVR's uint8_t narrowing still
    // applies. Masked once at this single choke point, matching that
    // project's own established fix.
    value &= 0xFF;

    // value 0 (all 8 pixels off) is a no-op - md_beginFrame()'s own
    // clear_screen(color_white) call already left every one of those
    // pixels showing the exact same white the column atlas's own value-0
    // tile would otherwise draw (see that function's own comment).
    if( value == 0 )
      return;

    select_region( value );
    draw_region_at( ORIGIN_X + col * TILE_SCALE, ORIGIN_Y + page * TILE_H );
}

// Only ever called by gbRenderFrame() when the runtime gbRealGrayColor
// toggle is on - see GRAYCOLUMNS_TEXTURE_ID's own comment above. Unlike
// md_drawColumn(), this draws on top of whatever's already on screen for
// this same (col,page) cell (real semi-transparent gray, not an opaque white
// background), so it must select its own distinct texture every call
// rather than relying on md_beginFrame()'s own COLUMNS_TEXTURE_ID
// selection to still be current.
void md_drawColumnGray( int col, int page, int value )
{
    value &= 0xFF;
    if( value == 0 )
      return;

    select_texture( GRAYCOLUMNS_TEXTURE_ID );
    select_region( value );
    draw_region_at( ORIGIN_X + col * TILE_SCALE, ORIGIN_Y + page * TILE_H );
}

void md_endFrame()
{
    end_frame();
}

